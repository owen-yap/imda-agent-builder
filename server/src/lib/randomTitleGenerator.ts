/**
 * Generates a random title by combining an adjective with an object noun
 * Example: "Curious Dolphin", "Radiant Lighthouse", "Mysterious Telescope"
 * @returns A random two-word title with capitalized words
 */
export function generateRandomSessionTitle(): string {
	const randomAdjective =
		adjectives[Math.floor(Math.random() * adjectives.length)];
	const randomObject = objects[Math.floor(Math.random() * objects.length)];

	return `${randomAdjective} ${randomObject}`;
}
